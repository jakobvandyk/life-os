interface PixelIconProps {
  name: string;
  size?: number;
  className?: string;
}

export default function PixelIcon({ name, size = 18, className = "" }: PixelIconProps) {
  const grid = ICONS[name];
  if (!grid) return <span className={className}>?</span>;

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${GRID_DIM} ${GRID_DIM}`}
      className={className}
      aria-hidden="true"
    >
      {grid.map((val, i) => {
        if (!val) return null;
        const x = i % GRID_DIM;
        const y = Math.floor(i / GRID_DIM);
        return (
          <rect
            key={i}
            x={x}
            y={y}
            width={1}
            height={1}
            fill="currentColor"
            shapeRendering="crispEdges"
          />
        );
      })}
    </svg>
  );
}

